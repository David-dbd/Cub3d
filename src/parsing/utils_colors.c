#include "../../includes/cub3d.h"

int	check_colors_range(int r, int g, int b)
{
	if (!(r >= 0 && r <= 255) || !(g >= 0 && g <= 255) || !(b >= 0 && b <= 255))
		return (0);
	return (1);
}